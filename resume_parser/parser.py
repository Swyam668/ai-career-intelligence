from src.nlp_profile_builder.skill_extractor import SkillExtractor
from src.nlp_profile_builder.extract_certifications import extract_certifications
from src.nlp_profile_builder.extract_education import extract_education
from src.nlp_profile_builder.extract_experience import extract_experience
from src.nlp_profile_builder.extract_title import extract_title
from src.nlp_profile_builder.extract_industry import extract_industry
from src.nlp_profile_builder.extract_skill_section import extract_candidates


def build_user_profile(resume_text, nlp_model):

    # skills = extract_skills(resume_text)
    skill_extractor = SkillExtractor(nlp_model, SKILLS)
    candidates = extract_candidates(resume_text)
    skills = skill_extractor.extract(candidates)
    cert_result = extract_certifications(resume_text)

    return {
        "job_title": extract_title(resume_text, nlp_model)["job_title"],
        # default value of 0 if not 'edu' is not found
        "education_level": extract_education(resume_text)["education_level"],
        "industry": extract_industry(resume_text),
        "company_size": "Medium",
        "location": "India",
        "remote_work": "No",

        "experience_years": extract_experience(resume_text)["experience_years"],
        "skills": skills,
        "skills_count": len(skills),
        "certifications": cert_result["certifications"],
        "certification_items": cert_result["certification_items"]
    }